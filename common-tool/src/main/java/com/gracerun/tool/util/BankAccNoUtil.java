    /**
     * 校验银行卡号正确性（Luhn算法）
     *
     * @param accNo 银行账户（卡号）
     * @return
     */
    public static boolean isBankAccNo(String accNo) {
        if (!StringUtils.hasText(accNo)) {
            return false;
        }
        int checkNumber = accNo.charAt(accNo.length() - 1) - '0';
        char[] charArr = accNo.toCharArray();
        int total = 0;
        for (int i = accNo.length() - 2; i >= 0; i -= 2) {
            int tmp = calculate((charArr[i] - '0') * 2);
            if (i == 0) {
                total += tmp;
            } else {
                total += tmp + (charArr[i - 1] - '0');
            }

        }
        if (total >= 0 && total < 9) {
            return checkNumber == 10 - total;
        } else {
            int low = total % 10;
            if (low != 0) {
                low = 10 - low;
            }
            return checkNumber == low;
        }
    }

    /**
     * 计算数字各位和
     *
     * @param number
     * @return
     */
    private static int calculate(int number) {
        int sum = 0;
        while (number != 0) {
            sum += number % 10;
            number = number / 10;
        }
        return sum;
    }

