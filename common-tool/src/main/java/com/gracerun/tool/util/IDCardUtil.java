    private final static int[] PARITY_BIT = {'1', '0', 'X', '9', '8', '7', '6', '5', '4', '3', '2'};
    private final static int[] POWER_LIST = {7, 9, 10, 5, 8, 4, 2, 1, 6, 3, 7, 9, 10, 5, 8, 4, 2};

    /**
     * 身份证验证
     *
     * @param idCard 号码内容
     * @return 是否有效 null和"" 都是false
     */
    public static boolean isIDCard(String idCard) {
        if (idCard == null || (idCard.length() != 15 && idCard.length() != 18)) {
            return false;
        }
        final char[] cs = idCard.toUpperCase().toCharArray();
        // 校验位数
        int power = 0;
        for (int i = 0; i < cs.length; i++) {
            if (i == cs.length - 1 && cs[i] == 'X') {
                break;// 最后一位可以 是X或x
            }
            if (cs[i] < '0' || cs[i] > '9') {
                return false;
            }
            if (i < cs.length - 1) {
                power += (cs[i] - '0') * POWER_LIST[i];
            }
        }

        // 校验区位码
        if (!zoneNum.containsKey(Integer.valueOf(idCard.substring(0, 2)))) {
            return false;
        }

        // 校验年份
        String year = idCard.length() == 15 ? getIdcardCalendar() + idCard.substring(6, 8) : idCard.substring(6, 10);

        final int intYear = Integer.parseInt(year);
        // 1900年的PASS，超过今年的PASS
        if (intYear < 1900 || intYear > Calendar.getInstance().get(Calendar.YEAR)) {
            return false;
        }

        // 校验月份
        String month = idCard.length() == 15 ? idCard.substring(8, 10) : idCard.substring(10, 12);
        final int intMonth = Integer.parseInt(month);
        if (intMonth < 1 || intMonth > 12) {
            return false;
        }

        // 校验天数
        String day = idCard.length() == 15 ? idCard.substring(10, 12) : idCard.substring(12, 14);
        final int intDay = Integer.parseInt(day);
        if (intDay < 1 || intDay > 31) {
            return false;
        }

        // 校验"校验码"
        if (idCard.length() == 15) {
            return true;
        }
        return cs[cs.length - 1] == PARITY_BIT[power % 11];
    }

    private static int getIdcardCalendar() {
        GregorianCalendar curDay = new GregorianCalendar();
        int curYear = curDay.get(Calendar.YEAR);
        return Integer.parseInt(String.valueOf(curYear).substring(2));
    }

